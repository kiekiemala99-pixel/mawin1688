export function articleTags(a: Article) {
  return a.tags?.length ? a.tags : a.keywords.split(",").map((s) => s.trim()).filter(Boolean).slice(0, 5);
}

export function allArticleTags() {
  const hit = new Set<string>();
  for (const a of ARTICLES) for (const t of articleTags(a)) hit.add(t);
  return [...hit];
}

export function articlesByTag(tag?: string) {
  if (!tag) return ARTICLES;
  return ARTICLES.filter((a) => articleTags(a).includes(tag));
}

export function getArticle(slug: string) {
  return ARTICLES.find((a) => a.slug === slug);
}

export function relatedArticles(slug: string, n = 3) {
  const cur = getArticle(slug);
  const rest = ARTICLES.filter((a) => a.slug !== slug);
  const curTags = cur ? articleTags(cur) : [];
  const tagged = rest.filter((a) => articleTags(a).some((t) => curTags.includes(t)));
  const same = rest.filter((a) => a.category === cur?.category);
  return [...tagged, ...same, ...rest].filter((a, i, arr) => arr.findIndex((x) => x.slug === a.slug) === i).slice(0, n);
}
